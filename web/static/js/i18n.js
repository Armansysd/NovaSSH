let currentLang = localStorage.getItem('novassh_lang') || 'en';

function setLanguage(lang) {
  if (!I18N_DICT[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('novassh_lang', lang);

  const isRTL = (lang === 'fa' || lang === 'ar');
  document.documentElement.setAttribute('dir', isRTL ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N_DICT[lang][key]) {
      el.innerText = I18N_DICT[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (I18N_DICT[lang][key]) {
      el.setAttribute('placeholder', I18N_DICT[lang][key]);
    }
  });

  const headerLangSelect = document.getElementById('header-lang-select');
  if (headerLangSelect) headerLangSelect.value = lang;

  const langSelect = document.getElementById('lang-select');
  if (langSelect) langSelect.value = lang;
}
